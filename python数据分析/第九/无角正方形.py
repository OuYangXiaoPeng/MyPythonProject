import turtle as t
t.setup(1000, 600)
t.pensize(2)
t.pencolor('black')

t.penup()
t.fd(50)
t.pendown()
t.fd(100)
t.penup()
t.fd(50)

t.seth(90)
t.fd(50)
t.pendown()
t.fd(100)
t.penup()
t.fd(50)

t.seth(180)
t.fd(50)
t.pendown()
t.fd(100)
t.penup()
t.fd(50)

t.seth(-90)
t.fd(50)
t.pendown()
t.fd(100)
t.pendown()

t.done()